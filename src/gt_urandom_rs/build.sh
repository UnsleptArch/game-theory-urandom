#!/bin/bash
# Stages src/gt_urandom_rs/gt_urandom_rs.rs into the guest kernel tree as
# an in-tree Rust sample and builds it.
#
# Why in-tree and not an out-of-tree M=... build like src/c-reference/Makefile
# does for the C module: Rust-for-Linux's out-of-tree module support is
# still experimental/fragile, while samples/rust/ is the well-supported,
# documented path and we fully control + already rebuild this disposable
# guest kernel tree anyway. The .rs source of truth stays here in the repo
# (build/ is gitignored); this script copies it in and patches the sample
# Kconfig/Makefile idempotently before building.
set -e
R=$(cd "$(dirname "$0")/../.." && pwd)
KDIR="$R/build/linux-src"
SRC="$R/src/gt_urandom_rs/gt_urandom_rs.rs"
DST="$KDIR/samples/rust/gt_urandom_rs.rs"
KCONFIG="$KDIR/samples/rust/Kconfig"
MAKEFILE="$KDIR/samples/rust/Makefile"

[ -d "$KDIR" ] || { echo "build.sh: $KDIR not found -- build the guest kernel first" >&2; exit 1; }

# Measure cost-to-fake inputs from this repo's own artifacts rather than
# hand-typing them into gt_urandom_rs.rs: how many added lines did the
# RDRAND QEMU patch actually need, versus zero for the sources that only
# need a documented stock CLI flag. Written as a generated `include!()`d
# file, not committed (src/gt_urandom_rs/*.generated.rs is gitignored) --
# it's recomputed every build, so it can't silently drift from the patch
# it's measuring.
RDRAND_PATCH_LINES=$(grep -c '^+[^+]' "$R/toolage/qemu-patch/0001-rdrand-poison.patch" 2>/dev/null || echo 0)
GEN="$R/src/gt_urandom_rs/cost_measurements.generated.rs"
cat > "$GEN" <<EOF
// Auto-generated by src/gt_urandom_rs/build.sh from this repo's own
// artifacts. Do not hand-edit -- it is overwritten, and not committed,
// every build. See build.sh for how each value is computed.
const MEASURED_RDRAND_PATCH_LINES: u32 = ${RDRAND_PATCH_LINES};
// virtio-rng and timing need zero QEMU source changes in this project's
// attack config (toolage/scripts/launch-attack.sh): both are documented, stock
// CLI flags (-object rng-random,... and -icount), never patched.
const MEASURED_VIRTIO_RNG_PATCH_LINES: u32 = 0;
const MEASURED_TIMING_PATCH_LINES: u32 = 0;
EOF
echo "GT: measured RDRAND patch lines = $RDRAND_PATCH_LINES (from toolage/qemu-patch/0001-rdrand-poison.patch)"

cp "$SRC" "$DST"
cp "$GEN" "$KDIR/samples/rust/cost_measurements.generated.rs"

if ! grep -q "SAMPLE_RUST_GT_URANDOM" "$KCONFIG"; then
  # Insert right after the "if SAMPLES_RUST" line.
  python3 - "$KCONFIG" <<'PYEOF'
import sys
path = sys.argv[1]
s = open(path).read()
marker = "if SAMPLES_RUST\n"
block = marker + """
config SAMPLE_RUST_GT_URANDOM
	tristate "game-theory-urandom entropy-source trust policy"
	help
	  This option builds the gt_urandom_rs sample: a game-theoretic
	  entropy-source trust policy against a hostile hypervisor. See
	  top-level CLAUDE.md in the game-theory-urandom repo.

	  To compile this as a module, choose M here:
	  the module will be called gt_urandom_rs.

	  If unsure, say N.
"""
assert marker in s, "marker not found in Kconfig"
s = s.replace(marker, block, 1)
open(path, "w").write(s)
PYEOF
fi

if ! grep -q "SAMPLE_RUST_GT_URANDOM" "$MAKEFILE"; then
  echo 'obj-$(CONFIG_SAMPLE_RUST_GT_URANDOM)		+= gt_urandom_rs.o' >> "$MAKEFILE"
fi

cd "$KDIR"
scripts/config -e SAMPLES -e SAMPLES_RUST --module SAMPLE_RUST_GT_URANDOM
make olddefconfig >/dev/null

# Rust samples build as part of the normal in-tree `make modules` (the
# Rust build rules aren't wired up for the external-module M=... path).
make -j"$(nproc)" modules 2>&1 | tee "$R/build/kbuild-rust-module.log" | tail -60
ls -la samples/rust/gt_urandom_rs.ko
cp samples/rust/gt_urandom_rs.ko "$R/src/gt_urandom_rs/gt_urandom_rs.ko"
echo "GT: built -> $R/src/gt_urandom_rs/gt_urandom_rs.ko"
